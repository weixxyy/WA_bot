#!/usr/bin/env bash
# Локальная веб-панель WA_bot (Linux / macOS).
#
# Панель поднимается на этом же компьютере (http://127.0.0.1:8765) и позволяет
# править текст сообщения, ссылки, расписание и список номеров. Пока панель
# работает, она держит блокировку бота, поэтому параллельно запускать main.py,
# run.sh или login.sh не нужно: второй процесс откажется стартовать.
#
# Аргументы пробрасываются в webapp.py:
#   ./web.sh                 # панель и автооткрытие браузера
#   ./web.sh --no-browser    # без автооткрытия браузера
#   ./web.sh --port 9000     # другой порт
#
# Закрытие окна терминала (SIGHUP) останавливает панель и освобождает блокировку.
#
# Переменные окружения:
#   VENV_DIR=.venv          имя каталога окружения (по умолчанию .venv)

set -euo pipefail

# Работаем из каталога проекта, а не из текущего каталога запуска.
cd "$(dirname "$0")"

VENV_DIR="${VENV_DIR:-.venv}"
VENV_PY="$VENV_DIR/bin/python"

if [ ! -x "$VENV_PY" ]; then
    echo "Не найдено виртуальное окружение $VENV_DIR ($VENV_PY)."
    echo "Сначала выполните ./setup.sh"
    exit 1
fi

exec "$VENV_PY" webapp.py "$@"
