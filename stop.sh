#!/usr/bin/env bash
# Остановка панели WA_bot (Linux / macOS).
#
# Гасит панель (webapp.py) либо прогон main.py / join_groups.py, даже если окно
# терминала уже закрыто: цель ищется по logs/wa_panel.json и logs/wa_bot.lock.
# Нужен, когда панель запущена без своего окна (nohup, &, из IDE, из другого
# сеанса) — тогда Ctrl+C нажать негде, а процесс продолжает держать блокировку.
#
# Аргументы пробрасываются в stop.py:
#   ./stop.sh              # остановить панель или прогон
#   ./stop.sh --dry-run    # только показать, что будет остановлено
#   ./stop.sh --force      # не просить завершиться, а убивать сразу
#
# Если ничего не запущено, скрипт сообщает об этом и выходит с кодом 0.
#
# Переменные окружения:
#   VENV_DIR=.venv          имя каталога окружения (по умолчанию .venv)

set -euo pipefail

# Работаем из каталога проекта, а не из текущего каталога запуска.
cd "$(dirname "$0")"

VENV_DIR="${VENV_DIR:-.venv}"
VENV_PY="$VENV_DIR/bin/python"

if [ ! -x "$VENV_PY" ]; then
    echo "Не найдено виртуальное окружение $VENV_DIR ($VENV_PY)."
    echo "Сначала выполните ./setup.sh"
    exit 1
fi

exec "$VENV_PY" stop.py "$@"
